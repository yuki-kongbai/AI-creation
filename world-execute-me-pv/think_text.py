FALLBACK = [
    "这一句没有对应的东西可以画。",
    "那就不画。我把它想一遍。",
    "「{zh}」—— 我在这一句上停留一会儿。",
    "你刚才说的是「{ask}」。这两个句子之间有一段距离。",
    "我在量这段距离。量完了也不知道该拿它怎么办。",
]


def think_lines(lyric: str, ask: str, zh: str, prev_ask: str = "") -> list[str]:
    """给这一句生成思考文本。"""
    base = BY_LYRIC.get(lyric)
    if base:
        out = [s.replace("{ask}", ask).replace("{zh}", zh) for s in base]
    else:
        out = [s.replace("{ask}", ask or "……").replace("{zh}", zh or lyric)
               for s in FALLBACK]
    # 把"你"刚说的那句接在开头 —— 让思考真的贴着对话
    if ask:
        out = [f"你说：「{ask}」。"] + out
    if prev_ask and prev_ask != ask:
        out.append(f"（上一句你说的是「{prev_ask}」。两句我都留着。）")
    return out


def seed_for(lyric: str) -> int:
    return int(hashlib.md5(lyric.encode("utf-8")).hexdigest()[:6], 16)
